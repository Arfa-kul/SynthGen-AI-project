import React, { useEffect, useState } from 'react';
import { Table, Download, Loader2, AlertCircle } from 'lucide-react';
import { api } from '../api';

export default function PreviewPage({ activeJob, setActiveTab }) {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [page, setPage] = useState(0);
  const PAGE_SIZE = 15;

  useEffect(() => {
    if (!activeJob || activeJob.status !== 'completed') return;
    setLoading(true);
    api.getJobPreview(activeJob.id, 200)
      .then(setData)
      .catch((e) => setError(e.message))
      .finally(() => setLoading(false));
  }, [activeJob?.id]);

  const handleDownload = (format) => {
    window.open(api.getDownloadUrl(activeJob.id, format), '_blank');
  };

  if (!activeJob || activeJob.status !== 'completed') {
    return (
      <div className="p-8 flex flex-col items-center justify-center h-64 text-slate-500 space-y-2">
        <Table className="w-10 h-10 text-slate-700" />
        <p>Generate synthetic data first to see the preview.</p>
      </div>
    );
  }

  if (loading) return (
    <div className="p-8 flex items-center justify-center h-64 space-x-3 text-slate-400">
      <Loader2 className="w-6 h-6 animate-spin text-brand-500" />
      <span>Loading synthetic data…</span>
    </div>
  );

  if (error) return (
    <div className="p-8 flex items-start space-x-3 text-rose-400">
      <AlertCircle className="w-5 h-5 mt-0.5" /><span>{error}</span>
    </div>
  );

  const totalPages = data ? Math.ceil(data.records.length / PAGE_SIZE) : 0;
  const pageRows = data ? data.records.slice(page * PAGE_SIZE, (page + 1) * PAGE_SIZE) : [];

  return (
    <div className="p-6 lg:p-8 space-y-6 max-w-7xl mx-auto">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-black text-white">Synthetic Data Preview</h1>
          <p className="text-slate-400 text-sm">
            Showing {data?.total_rows?.toLocaleString()} rows generated by{' '}
            <span className="text-brand-400 font-medium">{activeJob.model_type}</span>
          </p>
        </div>
        <div className="flex items-center space-x-2">
          <button
            id="btn-download-csv"
            onClick={() => handleDownload('csv')}
            className="flex items-center space-x-2 px-4 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-sm font-semibold transition-all"
          >
            <Download className="w-4 h-4" /> <span>CSV</span>
          </button>
          <button
            id="btn-download-json"
            onClick={() => handleDownload('json')}
            className="flex items-center space-x-2 px-4 py-2.5 rounded-xl bg-slate-700 hover:bg-slate-600 text-white text-sm font-semibold transition-all"
          >
            <Download className="w-4 h-4" /> <span>JSON</span>
          </button>
          <button
            id="btn-download-report"
            onClick={() => handleDownload('report')}
            className="flex items-center space-x-2 px-4 py-2.5 rounded-xl bg-slate-700 hover:bg-slate-600 text-white text-sm font-semibold transition-all"
          >
            <Download className="w-4 h-4" /> <span>Report</span>
          </button>
          <button
            id="btn-view-quality"
            onClick={() => setActiveTab('quality')}
            className="px-4 py-2.5 rounded-xl bg-gradient-to-r from-brand-600 to-indigo-600 text-white text-sm font-semibold transition-all"
          >
            Quality Analysis →
          </button>
        </div>
      </div>

      {/* Privacy notice */}
      <div className="p-3.5 rounded-xl border border-amber-500/20 bg-amber-950/20 text-xs text-amber-200/70">
        ⚠️ <strong className="text-amber-300">Privacy reminder:</strong> These records are synthetically generated by the SDV model and do not copy real individuals. However, statistical similarity to training data is expected and intentional. Do not treat synthetic data as truly anonymous without a formal privacy review.
      </div>

      {/* Data table */}
      <div className="glass-panel rounded-2xl overflow-hidden">
        <div className="overflow-x-auto">
          <table className="text-xs w-full">
            <thead>
              <tr className="border-b border-slate-800">
                <th className="text-left px-3 py-2.5 text-slate-500 font-semibold w-12">#</th>
                {(data?.columns || []).map((c) => (
                  <th key={c} className="text-left px-3 py-2.5 text-slate-400 font-semibold whitespace-nowrap">{c}</th>
                ))}
              </tr>
            </thead>
            <tbody>
              {pageRows.map((row, ri) => (
                <tr key={ri} className="border-b border-slate-900/50 hover:bg-slate-900/40 transition-colors">
                  <td className="px-3 py-2 text-slate-600">{page * PAGE_SIZE + ri + 1}</td>
                  {(data?.columns || []).map((c) => (
                    <td key={c} className="px-3 py-2 text-slate-300 whitespace-nowrap max-w-[140px] truncate">
                      {row[c] === null || row[c] === undefined
                        ? <span className="text-slate-600 italic">null</span>
                        : typeof row[c] === 'number' ? (Number.isInteger(row[c]) ? row[c] : row[c].toFixed(3)) : String(row[c])}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        {/* Pagination */}
        {totalPages > 1 && (
          <div className="flex items-center justify-between px-4 py-3 border-t border-slate-800/80 text-xs text-slate-400">
            <span>Showing {page * PAGE_SIZE + 1}–{Math.min((page + 1) * PAGE_SIZE, data.records.length)} of {data.records.length} rows</span>
            <div className="flex items-center space-x-1">
              <button
                disabled={page === 0}
                onClick={() => setPage(p => p - 1)}
                className="px-3 py-1 rounded-lg bg-slate-800 hover:bg-slate-700 disabled:opacity-40 disabled:cursor-not-allowed transition-colors"
              >← Prev</button>
              <span className="px-2">{page + 1} / {totalPages}</span>
              <button
                disabled={page >= totalPages - 1}
                onClick={() => setPage(p => p + 1)}
                className="px-3 py-1 rounded-lg bg-slate-800 hover:bg-slate-700 disabled:opacity-40 disabled:cursor-not-allowed transition-colors"
              >Next →</button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
